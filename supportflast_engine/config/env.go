// Get lấy giá trị biến môi trường hoặc trả về giá trị mặc định nếu rỗng
func Get(key, defaultValue string) string {
	if val := strings.TrimSpace(os.Getenv(key)); val != "" {
		return val
	}
	return defaultValue
}

// GetInt lấy giá trị kiểu số nguyên hoặc trả về giá trị mặc định nếu lỗi/rỗng
func GetInt(key string, defaultValue int) int {
	valStr := strings.TrimSpace(os.Getenv(key))
	if valStr == "" {
		return defaultValue
	}
	val, err := strconv.Atoi(valStr)
	if err != nil {
		return defaultValue
	}
	return val
}

// GetBool lấy giá trị kiểu boolean hoặc trả về giá trị mặc định nếu lỗi/rỗng
func GetBool(key string, defaultValue bool) bool {
	valStr := strings.ToLower(strings.TrimSpace(os.Getenv(key)))
	if valStr == "" {
		return defaultValue
	}
	return valStr == "1" || valStr == "true" || valStr == "yes" || valStr == "on"
}

// IsProduction kiểm tra xem hệ thống có đang chạy ở chế độ production hay không
func IsProduction() bool {
	env := strings.ToLower(Get("ENV", "production"))
	return env == "production" || env == "prod"
}
