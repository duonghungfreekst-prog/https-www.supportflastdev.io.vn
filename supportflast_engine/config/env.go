// ResetForTest đặt lại trạng thái nạp file .env phục vụ các kịch bản kiểm thử độc lập
func ResetForTest() {
	loadOnce = sync.Once{}
	loadedEnvPath = ""
	loadedCount = 0
}

// InitEnv tự động kiểm tra, khởi tạo và nạp file '.env' vào môi trường tiến trình.
// 1. Nếu file '.env' chưa tồn tại, tự động sao chép từ '.env.example' (hoặc sinh cấu hình chuẩn)
//    và sinh JWT_SECRET, CLOUDPOOL_MASTER_KEY ngẫu nhiên độ phức tạp cao bằng CSPRNG.
// 2. Nạp toàn bộ các biến môi trường từ '.env' vào tiến trình mà không ghi đè biến hệ thống đã có.
// 3. Hoàn toàn sử dụng Go Standard Library, không phụ thuộc bất kỳ thư viện ngoài nào.
func InitEnv() error {
	var initErr error
	loadOnce.Do(func() {
		// 1. Tìm kiếm file .env sẵn có
		envPath := findEnvFile()

		// 2. Nếu chưa có file .env, tự động tạo từ .env.example hoặc sinh cấu hình chuẩn
		if envPath == "" {
			createdPath, err := autoGenerateEnv()
			if err != nil {
				log.Printf("[CONFIG] [ENV] [WARN] Không thể tự động tạo file '.env': %v", err)
			} else {
				envPath = createdPath
			}
		}

		// 3. Nếu tìm thấy hoặc vừa tạo thành công file .env, tiến hành nạp vào môi trường
		if envPath != "" {
			count, err := LoadEnvFile(envPath)
			if err != nil {
				log.Printf("[CONFIG] [ENV] [ERROR] Lỗi khi nạp file '%s': %v", envPath, err)
				initErr = err
				return
			}
			loadedEnvPath = envPath
			loadedCount = count

			envMode := Get("ENV", "production")
			port := Get("PORT", "8080")
			domain := Get("DOMAIN", "supportflastdev.io.vn")

			log.Printf("[CONFIG] [ENV] Đã nạp thành công %d biến môi trường từ file: '%s'", count, envPath)
			log.Printf("[CONFIG] [ENV] Thiết lập hoạt động: ENV=%s | PORT=%s | DOMAIN=%s", envMode, port, domain)
		} else {
			log.Println("[CONFIG] [ENV] [INFO] Không tìm thấy file '.env' hoặc '.env.example', sử dụng biến môi trường hệ thống mặc định.")
		}
	})
	return initErr
}

// GetLoadedEnvPath trả về đường dẫn file .env đã được nạp
func GetLoadedEnvPath() string {
	return loadedEnvPath
}

// GetLoadedCount trả về số lượng biến môi trường đã được nạp từ file .env
func GetLoadedCount() int {
	return loadedCount
}

// findEnvFile tìm file .env tại các vị trí ưu tiên
func findEnvFile() string {
	if custom := os.Getenv("ENV_FILE"); custom != "" {
		if fileExists(custom) {
			return custom
		}
		return ""
	}

	if customDir := os.Getenv("ENV_DIR"); customDir != "" {
		target := filepath.Join(customDir, ".env")
		if fileExists(target) {
			return target
		}
		return ""
	}

	candidates := []string{
		".env",
		filepath.Join("..", ".env"),
		filepath.Join("..", "..", ".env"),
		`f:\supportflast.dev\.env`,
	}

	// Thêm đường dẫn tương đối từ thư mục binary thực thi
	if exe, err := os.Executable(); err == nil {
		exeDir := filepath.Dir(exe)
		candidates = append(candidates,
			filepath.Join(exeDir, ".env"),
			filepath.Join(exeDir, "..", ".env"),
		)
	}

	for _, path := range candidates {
		if fileExists(path) {
			if abs, err := filepath.Abs(path); err == nil {
				return abs
			}
			return path
		}
	}
	return ""
}

